class DUTSDatasetSize(Dataset):
    def __init__(self, img_dir, mask_dir, size=320):
        self.img_dir = img_dir
        self.mask_dir = mask_dir
        self.size = size
        self.names = sorted(os.listdir(img_dir))

    def set_size(self, size):
        self.size = size

    def __len__(self):
        return len(self.names)

    def __getitem__(self, idx):
        name = self.names[idx]
        stem = os.path.splitext(name)[0]

        img = Image.open(os.path.join(self.img_dir, name)).convert("RGB")
        mask_path = os.path.join(self.mask_dir, stem + ".png")
        if not os.path.exists(mask_path):
            mask_path = os.path.join(self.mask_dir, stem + ".jpg")
        mask = Image.open(mask_path).convert("L")

        img = img.resize((self.size, self.size), Image.BILINEAR)
        mask = mask.resize((self.size, self.size), Image.NEAREST)

        if random.random() < 0.5:
            img = TF.hflip(img)
            mask = TF.hflip(mask)
        if random.random() < 0.3:
            img = TF.adjust_brightness(img, random.uniform(0.8, 1.2))
        if random.random() < 0.3:
            img = TF.adjust_contrast(img, random.uniform(0.7, 1.2))

        img = TF.normalize(TF.to_tensor(img),
                           mean=[0.485, 0.456, 0.406],
                           std=[0.229, 0.224, 0.225])
        mask = (TF.to_tensor(mask) > 0.5).float()
        return img, mask

import torch
import torch.nn as nn
import torch.nn.functional as F
from torchvision.models import mobilenet_v3_small, MobileNet_V3_Small_Weights

class LiteSaliencyNet(nn.Module):
    def __init__(self):
        super().__init__()
        backbone = mobilenet_v3_small(weights=MobileNet_V3_Small_Weights.DEFAULT)
        f = backbone.features

        self.stage0 = f[0:2]
        self.stage1 = f[2:4]
        self.stage2 = f[4:9]
        self.stage3 = f[9:]

        self.lat0 = nn.Conv2d(16,  32, 1)
        self.lat1 = nn.Conv2d(24,  32, 1)
        self.lat2 = nn.Conv2d(48,  32, 1)
        self.lat3 = nn.Conv2d(576, 32, 1)

        self.smooth2 = nn.Sequential(
            nn.Conv2d(32, 32, 3, padding=1, bias=False),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
        )
        self.smooth1 = nn.Sequential(
            nn.Conv2d(32, 32, 3, padding=1, bias=False),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
        )
        self.smooth0 = nn.Sequential(
            nn.Conv2d(32, 32, 3, padding=1, bias=False),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
        )

        self.head = nn.Sequential(
            nn.Conv2d(32, 16, 3, padding=1, bias=False),
            nn.BatchNorm2d(16),
            nn.ReLU(inplace=True),
            nn.Conv2d(16, 1, 1),
        )

    def forward(self, x):
        c0 = self.stage0(x)
        c1 = self.stage1(c0)
        c2 = self.stage2(c1)
        c3 = self.stage3(c2)

        p0 = self.lat0(c0)
        p1 = self.lat1(c1)
        p2 = self.lat2(c2)
        p3 = self.lat3(c3)

        p2 = p2 + F.interpolate(p3, size=p2.shape[-2:], mode='bilinear', align_corners=False)
        p2 = self.smooth2(p2)
        p1 = p1 + F.interpolate(p2, size=p1.shape[-2:], mode='bilinear', align_corners=False)
        p1 = self.smooth1(p1)
        p0 = p0 + F.interpolate(p1, size=p0.shape[-2:], mode='bilinear', align_corners=False)
        p0 = self.smooth0(p0)

        out = self.head(p0)
        out = F.interpolate(out, size=x.shape[-2:], mode='bilinear', align_corners=False)
        return torch.sigmoid(out)

