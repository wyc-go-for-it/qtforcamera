class BCEDiceLoss(nn.Module):
    def __init__(self, bce_w=1.0, dice_w=1.0):
        super().__init__()
        self.bce_w = bce_w
        self.dice_w = dice_w
    def forward(self, pred, target):
        bce = F.binary_cross_entropy(pred, target)
        pred_f = pred.view(pred.size(0), -1)
        target_f = target.view(target.size(0), -1)
        inter = (pred_f * target_f).sum(1)
        union = pred_f.sum(1) + target_f.sum(1) + 1e-6
        dice = 1 - (2 * inter / union).mean()
        return self.bce_w * bce + self.dice_w * dice

