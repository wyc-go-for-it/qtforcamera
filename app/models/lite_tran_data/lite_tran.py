n_train = len(full) - n_val
train_ds, val_ds = random_split(full, [n_train, n_val],
                                 generator=torch.Generator().manual_seed(42))

train_loader = DataLoader(train_ds, batch_size=8, shuffle=True,
                          num_workers=2, pin_memory=True, drop_last=True)
val_loader   = DataLoader(val_ds, batch_size=8, shuffle=False,
                          num_workers=2, pin_memory=True)

# 模型
net = LiteSaliencyNet().to(device)

EPOCHS = 30
optimizer = torch.optim.AdamW(net.parameters(), lr=1e-3, weight_decay=1e-4)
scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=EPOCHS)
criterion = BCEDiceLoss().to(device)

# ===== 断点续训 =====
CKPT = "/content/lite_320_ckpt.pth"
start_epoch = 0
best_iou = 0.0

if os.path.exists(CKPT):
    ckpt = torch.load(CKPT, map_location=device)
    net.load_state_dict(ckpt["model"])
    optimizer.load_state_dict(ckpt["optimizer"])
    scheduler.load_state_dict(ckpt["scheduler"])
    start_epoch = ckpt["epoch"] + 1
    best_iou = ckpt["best_iou"]
    print(f"resume from epoch {start_epoch}, best IoU={best_iou:.4f}")

def compute_iou(pred, target):
    pred = (pred > 0.5).float()
    inter = (pred * target).sum()
    union = pred.sum() + target.sum() - inter + 1e-6
    return (inter / union).item()

for epoch in range(start_epoch, EPOCHS):
    net.train()
    t0 = time.time()
    train_loss = 0.0
    for imgs, masks in train_loader:
        imgs, masks = imgs.to(device, non_blocking=True), masks.to(device, non_blocking=True)
        optimizer.zero_grad()
        pred = net(imgs)
        loss = criterion(pred, masks)
        loss.backward()
        optimizer.step()
        train_loss += loss.item()
    scheduler.step()

    # 验证
    net.eval()
    val_loss = 0.0
    val_iou = 0.0
    with torch.no_grad():
        for imgs, masks in val_loader:
            imgs, masks = imgs.to(device), masks.to(device)
            pred = net(imgs)
            val_loss += criterion(pred, masks).item()
            val_iou  += compute_iou(pred, masks)

    train_loss /= len(train_loader)
    val_loss   /= len(val_loader)
    val_iou    /= len(val_loader)

    print(f"[{epoch+1:02d}/{EPOCHS}] "
          f"train_loss={train_loss:.4f} val_loss={val_loss:.4f} "
          f"IoU={val_iou:.4f} time={time.time()-t0:.1f}s")

    # 保存 checkpoint
    torch.save({
        "model": net.state_dict(),
        "optimizer": optimizer.state_dict(),
        "scheduler": scheduler.state_dict(),
        "epoch": epoch,
        "best_iou": best_iou,
    }, CKPT)

    # 保存 best
    if val_iou > best_iou:
        best_iou = val_iou
        torch.save(net.state_dict(), "/content/lite_320_best.pth")
        print(f"  ✅ saved best IoU={best_iou:.4f}")

print("done, best IoU:", best_iou)

