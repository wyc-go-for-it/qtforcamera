def get_bytes(x):
    """从 dict / bytes / PIL 中取出二进制"""
    if isinstance(x, dict):
        return x["bytes"]
    if isinstance(x, bytes):
        return x
    if isinstance(x, Image.Image):
        buf = io.BytesIO()
        x.save(buf, format="PNG")
        return buf.getvalue()
    raise ValueError(f"unknown: {type(x)}")

